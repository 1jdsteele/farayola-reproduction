from pathlib import Path
import argparse
import hashlib
import importlib.metadata

import numpy as np
import pandas as pd

from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix

from aif360.datasets import BinaryLabelDataset
from aif360.metrics import ClassificationMetric


# ---------------------------------------------------------------------
# Command line
# ---------------------------------------------------------------------

parser = argparse.ArgumentParser()
parser.add_argument("--tag", required=True)

args = parser.parse_args()
tag = args.tag

if not tag.replace("_", "").replace("-", "").isalnum():
    raise ValueError("Invalid tag")


# ---------------------------------------------------------------------
# Paths / protocol
# ---------------------------------------------------------------------

RUN_ROOT = Path(__file__).resolve().parents[1]

DATA_PATH = RUN_ROOT / "data" / "compas_farayola_numeric.csv"

MANIFEST_PATH = (
    RUN_ROOT
    / "metadata"
    / "fixed_split_manifest_seed101.csv"
)

METADATA_DIR = RUN_ROOT / "metadata"

EXPECTED_DATA_SHA256 = (
    "6654c9ba30e95dd05567189302e033585a7c5ffb2a93fda284a7bf22e57f160e"
)

EXPECTED_TRAIN_ID_SHA256 = (
    "db883dde9864689948334065e30b9aaf628d4e406c7d565df492b5cfa96021cb"
)

EXPECTED_TEST_ID_SHA256 = (
    "a9d9f03486e3577a0eac1345527af731b9f473450cb33a53a0330c71d7a42de5"
)

SPLIT_SEED = 101
ALGORITHM_SEEDS = list(range(101, 121))

privileged_group = [{"race": 1}]
unprivileged_group = [{"race": 0}]


# ---------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------

def array_sha256(array, dtype):
    normalized = np.ascontiguousarray(
        np.asarray(array, dtype=dtype)
    )

    return hashlib.sha256(
        normalized.tobytes()
    ).hexdigest()


# ---------------------------------------------------------------------
# Input
# ---------------------------------------------------------------------

data = pd.read_csv(DATA_PATH)
manifest = pd.read_csv(MANIFEST_PATH)

assert data.shape == (5278, 12)

assert data["two_year_recid"].value_counts().to_dict() == {
    0: 2795,
    1: 2483,
}

assert data["race"].value_counts().to_dict() == {
    0: 3175,
    1: 2103,
}

data_sha256 = hashlib.sha256(
    DATA_PATH.read_bytes()
).hexdigest()

assert data_sha256 == EXPECTED_DATA_SHA256


# ---------------------------------------------------------------------
# Recover canonical fixed split
# ---------------------------------------------------------------------

train_manifest = (
    manifest.loc[manifest["split"] == "train"]
    .sort_values("split_order")
)

test_manifest = (
    manifest.loc[manifest["split"] == "test"]
    .sort_values("split_order")
)

train_ids = train_manifest["row_id"].to_numpy(dtype=np.int64)
test_ids = test_manifest["row_id"].to_numpy(dtype=np.int64)

assert len(train_ids) == 3694
assert len(test_ids) == 1584
assert len(set(train_ids).intersection(set(test_ids))) == 0
assert len(set(train_ids).union(set(test_ids))) == len(data)

train_id_sha256 = array_sha256(train_ids, np.int64)
test_id_sha256 = array_sha256(test_ids, np.int64)

assert train_id_sha256 == EXPECTED_TRAIN_ID_SHA256
assert test_id_sha256 == EXPECTED_TEST_ID_SHA256


# Preserve exact split order generated by train_test_split.
train_df = data.iloc[train_ids].reset_index(drop=True)
test_df = data.iloc[test_ids].reset_index(drop=True)

X_train = train_df.drop(columns=["two_year_recid"])
y_train = train_df["two_year_recid"]

X_test = test_df.drop(columns=["two_year_recid"])
y_test = test_df["two_year_recid"]


# ---------------------------------------------------------------------
# Fixed-split integrity
# ---------------------------------------------------------------------

assert int((X_train["race"] == 0).sum()) == 2222
assert int((X_train["race"] == 1).sum()) == 1472

assert int((X_test["race"] == 0).sum()) == 953
assert int((X_test["race"] == 1).sum()) == 631

assert int((y_train == 0).sum()) == 1914
assert int((y_train == 1).sum()) == 1780

assert int((y_test == 0).sum()) == 881
assert int((y_test == 1).sum()) == 703


# ---------------------------------------------------------------------
# AIF360 true test dataset
# ---------------------------------------------------------------------

test_bld = BinaryLabelDataset(
    df=test_df,
    label_names=["two_year_recid"],
    favorable_label=1,
    unfavorable_label=0,
    protected_attribute_names=["race"],
    privileged_protected_attributes=privileged_group,
)


# ---------------------------------------------------------------------
# Negative-control repetitions
# ---------------------------------------------------------------------

rows = []

for algorithm_seed in ALGORITHM_SEEDS:

    # IMPORTANT:
    # algorithm_seed is recorded but intentionally NOT supplied to
    # LogisticRegression. NONE has no intended stochastic component.
    classifier = LogisticRegression()

    classifier.fit(
        X_train,
        y_train,
    )

    labels = classifier.predict(
        X_test
    ).astype(int)

    scores = classifier.predict_proba(
        X_test
    )[:, 1].astype(float)

    pred_df = test_df.copy()
    pred_df["two_year_recid"] = labels

    pred_bld = BinaryLabelDataset(
        df=pred_df,
        label_names=["two_year_recid"],
        favorable_label=1,
        unfavorable_label=0,
        protected_attribute_names=["race"],
        privileged_protected_attributes=privileged_group,
    )

    # Preserve continuous classifier scores for diagnostics.
    pred_bld.scores = scores.reshape(-1, 1)

    metric = ClassificationMetric(
        test_bld,
        pred_bld,
        unprivileged_groups=unprivileged_group,
        privileged_groups=privileged_group,
    )

    accuracy = float(
        accuracy_score(
            y_test,
            labels,
        )
    )

    tn, fp, fn, tp = confusion_matrix(
        y_test,
        labels,
        labels=[0, 1],
    ).ravel()

    rows.append({
        "configuration": "NONE",
        "split_seed": SPLIT_SEED,
        "algorithm_seed": algorithm_seed,

        "train_rows": len(train_ids),
        "test_rows": len(test_ids),

        "train_row_id_sha256": train_id_sha256,
        "test_row_id_sha256": test_id_sha256,

        "prediction_sha256": array_sha256(
            labels,
            np.int64,
        ),

        "score_sha256": array_sha256(
            scores,
            np.float64,
        ),

        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
        "tp": int(tp),

        "accuracy": accuracy,

        "disparate_impact": float(
            metric.disparate_impact()
        ),

        "statistical_parity_difference": float(
            metric.statistical_parity_difference()
        ),

        "equal_opportunity_difference": float(
            metric.equal_opportunity_difference()
        ),

        "predictive_equality_difference": float(
            metric.false_positive_rate_difference()
        ),

        "logreg_iterations": int(
            classifier.n_iter_[0]
        ),
    })


results = pd.DataFrame(rows)


# ---------------------------------------------------------------------
# Negative-control assertions
# ---------------------------------------------------------------------

assert len(results) == 20

assert results["split_seed"].nunique() == 1
assert results["split_seed"].iloc[0] == 101

assert results["train_row_id_sha256"].nunique() == 1
assert results["test_row_id_sha256"].nunique() == 1

assert results["prediction_sha256"].nunique() == 1, (
    "NONE unexpectedly produced different hard predictions"
)

assert results["score_sha256"].nunique() == 1, (
    "NONE unexpectedly produced different probability scores"
)

metric_columns = [
    "accuracy",
    "disparate_impact",
    "statistical_parity_difference",
    "equal_opportunity_difference",
    "predictive_equality_difference",
]

for column in metric_columns:
    assert results[column].nunique() == 1, (
        f"NONE unexpectedly varied for {column}"
    )


# ---------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------

summary_rows = []

for metric_name in metric_columns:
    values = results[metric_name]

    summary_rows.append({
        "configuration": "NONE",
        "metric": metric_name,
        "n": len(values),
        "mean": float(values.mean()),
        "sample_std": float(values.std(ddof=1)),
        "min": float(values.min()),
        "max": float(values.max()),
    })

summary = pd.DataFrame(summary_rows)


# ---------------------------------------------------------------------
# Save
# ---------------------------------------------------------------------

results_path = (
    METADATA_DIR
    / f"none_per_seed_results_{tag}.csv"
)

summary_path = (
    METADATA_DIR
    / f"none_aggregate_summary_{tag}.csv"
)

results.to_csv(
    results_path,
    index=False,
    float_format="%.15g",
)

summary.to_csv(
    summary_path,
    index=False,
    float_format="%.15g",
)


# ---------------------------------------------------------------------
# Human-readable output
# ---------------------------------------------------------------------

print("=" * 100)
print("RUN 036 — NONE — FIXED-SPLIT RANDOM-SEED SENSITIVITY")
print("=" * 100)

print()
print("ENVIRONMENT")
print("-----------")
print("Python configuration: main .venv")
print("NumPy:", importlib.metadata.version("numpy"))
print("pandas:", importlib.metadata.version("pandas"))
print("scikit-learn:", importlib.metadata.version("scikit-learn"))
print("AIF360:", importlib.metadata.version("aif360"))

print()
print("PROTOCOL")
print("--------")
print("Configuration: NONE")
print("Split seed:", SPLIT_SEED)
print("Algorithm seeds:", ALGORITHM_SEEDS)
print("Algorithm seed affects model: False")
print("Train rows:", len(train_ids))
print("Test rows:", len(test_ids))
print("Train row-ID SHA256:", train_id_sha256)
print("Test row-ID SHA256:", test_id_sha256)

print()
print("NEGATIVE CONTROL")
print("----------------")
print(
    "Unique prediction hashes:",
    results["prediction_sha256"].nunique(),
)
print(
    "Unique score hashes:",
    results["score_sha256"].nunique(),
)

print()
print("METRICS")
print("-------")

r = results.iloc[0]

print(f"Accuracy: {r['accuracy']:.12f}")
print(f"DI:       {r['disparate_impact']:.12f}")
print(f"SPD:      {r['statistical_parity_difference']:.12f}")
print(f"EOD:      {r['equal_opportunity_difference']:.12f}")
print(f"PED:      {r['predictive_equality_difference']:.12f}")

print(
    "CM:       "
    f"[{int(r['tn'])},{int(r['fp'])},"
    f"{int(r['fn'])},{int(r['tp'])}]"
)

print()
print("RESULT")
print("------")
print("NONE is invariant across all 20 algorithm-seed records.")
print("Fixed-split negative control: PASS")

print()
print("Saved:")
print(results_path)
print(summary_path)
